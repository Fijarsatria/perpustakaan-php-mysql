-- Skema kompatibel dengan materi perpustakaan sebelumnya.
CREATE DATABASE IF NOT EXISTS perpustakaan CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE perpustakaan;
CREATE TABLE IF NOT EXISTS buku (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 Judul VARCHAR(150) NOT NULL,
 Penulis VARCHAR(100) NOT NULL,
 Penerbit VARCHAR(100) NOT NULL DEFAULT '',
 `Tahun Terbit` YEAR NOT NULL,
 Stok INT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
